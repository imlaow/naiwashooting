// Bakes King Naiwa's silhouette (public/assets/boss.png) into src/dreamMask.js: the dream maps'
// ground is that picture, and a server has to know where it ends without decoding a PNG.
// The mask is the image's alpha at 1/5 size, one byte a cell; Dream samples it bilinearly.
//
//   node tools/bake-dream-mask.mjs          writes src/dreamMask.js
//   node tools/bake-dream-mask.mjs --info   also prints where the eyes, tongue and belly are
//
// Rebaking after the image changes moves the maps' edges: bump PROTOCOL (src/sim/protocol.js).
import sharp from 'sharp';
import { writeFileSync } from 'node:fs';

const SRC = new URL('../public/assets/boss.png', import.meta.url);
const OUT = new URL('../src/dreamMask.js', import.meta.url);
const CELL = 5;

const img = sharp(SRC.pathname).ensureAlpha();
const { width, height } = await img.metadata();
const w = Math.ceil(width / CELL), h = Math.ceil(height / CELL);
const alpha = await img.clone().extractChannel('alpha').resize(w, h, { fit: 'fill', kernel: 'cubic' }).raw().toBuffer();

writeFileSync(OUT, `// Generated by tools/bake-dream-mask.mjs from public/assets/boss.png: don't edit.
// King Naiwa's alpha, ${w} × ${h} cells of ${CELL} image pixels, one byte each, base64.
export const MASK = { imgW: ${width}, imgH: ${height}, cell: ${CELL}, w: ${w}, h: ${h}, data: '${alpha.toString('base64')}' };
`);
console.log(`src/dreamMask.js: ${w} x ${h} cells from ${width} x ${height}`);

if (process.argv.includes('--info')) {
  const { data } = await img.clone().raw().toBuffer({ resolveWithObject: true });
  const acc = {};
  const add = (k, x, y) => {
    const a = (acc[k] ??= { n: 0, x0: 1e9, x1: 0, y0: 1e9, y1: 0, sx: 0, sy: 0 });
    a.n++; a.sx += x; a.sy += y;
    a.x0 = Math.min(a.x0, x); a.x1 = Math.max(a.x1, x); a.y0 = Math.min(a.y0, y); a.y1 = Math.max(a.y1, y);
  };
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    const p = (y * width + x) * 4, r = data[p], g = data[p + 1], b = data[p + 2];
    if (data[p + 3] < 128) continue;
    if (g > r + 30 && g > b + 30) add(x < width / 2 ? 'eyeL' : 'eyeR', x, y);
    else if (r > 200 && b > 110 && g < 160 && y < 200) add('tongue', x, y);
    else if (r > 225 && g > 190 && b > 130) add('belly', x, y);
  }
  for (const [k, a] of Object.entries(acc)) console.log(k, a.n, 'centre', Math.round(a.sx / a.n), Math.round(a.sy / a.n), 'box', a.x0, a.x1, a.y0, a.y1);
  for (let y = 0; y < h; y += 3) console.log(Array.from({ length: w }, (_, x) => (alpha[y * w + x] > 127 ? '#' : '.')).join(''));
}
